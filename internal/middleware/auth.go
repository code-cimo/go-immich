package middleware

import (
	"errors"
	"log"
	"net/http"
	"strings"

	"github.com/gin-gonic/gin"
	"github.com/golang-jwt/jwt/v5"

	"go-immich/internal/models"
	"go-immich/internal/repository"
)

// Gin context keys shared between the auth middleware and handlers.
const (
	CtxUserID = "authUserID"
	CtxUser   = "authUser"
	CtxIsAdmin = "authIsAdmin"
)

// Claims is the JWT payload. Field names mirror the values the Immich clients
// expect after decoding their own token (sub == user id).
type Claims struct {
	Email   string `json:"email"`
	Name    string `json:"name"`
	IsAdmin bool   `json:"isAdmin"`
	jwt.RegisteredClaims
}

// AuthMiddleware validates Bearer JWTs (and x-api-key style keys passed as
// ?key= which older Immich mobile builds append to asset URLs).
type AuthMiddleware struct {
	secret []byte
	users  *repository.UserRepo
}

// NewAuthMiddleware wires the shared secret and the user lookup used to make
// sure tokens belonging to deleted users are rejected immediately.
func NewAuthMiddleware(secret string, users *repository.UserRepo) *AuthMiddleware {
	return &AuthMiddleware{secret: []byte(secret), users: users}
}

// Require aborts with 401 AuthenticationException when no valid token is
// present; the error body matches NestJS so client interceptors behave the same.
func (a *AuthMiddleware) Require() gin.HandlerFunc {
	return func(c *gin.Context) {
		tokenStr := extractToken(c)
		if tokenStr == "" {
			abortUnauthorized(c)
			return
		}

		claims, err := a.parse(tokenStr)
		if err != nil {
			log.Printf("auth: token rejected: %v", err)
			abortUnauthorized(c)
			return
		}

		// Defence in depth: confirm the subject still exists & is active.
		u, err := a.users.ByID(c.Request.Context(), claims.Subject)
		if err != nil {
			log.Printf("auth: user lookup failed for %s: %v", claims.Subject, err)
			abortUnauthorized(c)
			return
		}
		if u == nil || !u.IsActive {
			abortUnauthorized(c)
			return
		}

		c.Set(CtxUserID, u.ID)
		c.Set(CtxUser, u)
		c.Set(CtxIsAdmin, u.IsAdmin)
		c.Next()
	}
}

// Optional behaves like Require but lets anonymous traffic through - used on
// endpoints the official server also exposes without auth (server-info).
func (a *AuthMiddleware) Optional() gin.HandlerFunc {
	return func(c *gin.Context) {
		tokenStr := extractToken(c)
		if tokenStr == "" {
			c.Next()
			return
		}
		if claims, err := a.parse(tokenStr); err == nil {
			if u, err := a.users.ByID(c.Request.Context(), claims.Subject); err == nil && u != nil {
				c.Set(CtxUserID, u.ID)
				c.Set(CtxUser, u)
				c.Set(CtxIsAdmin, u.IsAdmin)
			}
		}
		c.Next()
	}
}

func (a *AuthMiddleware) parse(tokenStr string) (*Claims, error) {
	tok, err := jwt.ParseWithClaims(tokenStr, &Claims{}, func(t *jwt.Token) (any, error) {
		// Pin the algorithm: refuse anything that is not HMAC-SHA256.
		if _, ok := t.Method.(*jwt.SigningMethodHMAC); !ok {
			return nil, errors.New("unexpected signing method")
		}
		return a.secret, nil
	}, jwt.WithValidMethods([]string{"HS256"}))
	if err != nil {
		return nil, err
	}
	claims, ok := tok.Claims.(*Claims)
	if !ok || !tok.Valid {
		return nil, errors.New("invalid token claims")
	}
	return claims, nil
}

// extractToken pulls the credential from, in order: Authorization: Bearer,
// x-api-key header, then the ?key= query parameter (thumbnail/original URLs
// generated by older clients cannot carry headers).
func extractToken(c *gin.Context) string {
	if h := c.GetHeader("Authorization"); h != "" {
		if len(h) > 7 && strings.EqualFold(h[:7], "bearer ") {
			return strings.TrimSpace(h[7:])
		}
		// some clients send the raw JWT without scheme
		return strings.TrimSpace(h)
	}
	if k := c.GetHeader("x-api-key"); k != "" {
		return k
	}
	return c.Query("key")
}

// CurrentUser returns the authenticated user previously stored by Require().
func CurrentUser(c *gin.Context) (*models.User, bool) {
	v, ok := c.Get(CtxUser)
	if !ok {
		return nil, false
	}
	u, ok := v.(*models.User)
	return u, ok
}

func abortUnauthorized(c *gin.Context) {
	// Body shape of the NestJS "UnauthorizedException".
	c.AbortWithStatusJSON(http.StatusUnauthorized, gin.H{
		"error":     "Unauthorized",
		"message":   "Invalid token",
		"statusCode": http.StatusUnauthorized,
	})
}
